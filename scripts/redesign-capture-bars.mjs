// Captures the app's REAL top bars (Library #lib-top, Editor #fx-deskbar) and the Library filters panel as rendered markup, so the
// redesign playground restyles the actual controls instead of a re-drawn mockup (redesign is look-only).
// Inline handlers are stripped; ids, classes, titles, aria-labels and rendered icon SVGs are kept.
// Usage: node scripts/build-desktop.mjs && node scripts/redesign-capture-bars.mjs
import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { DETERMINISTIC_LAUNCH_ARGS, DETERMINISTIC_CONTEXT_OPTIONS } from '../test/wireframe_diff_lib.mjs';

const ROOT = process.cwd();
const server = createServer(async (req, res) => {
  try { const u = decodeURIComponent(req.url.split('?')[0]); const d = await readFile(path.join(ROOT, u.slice(1))); res.writeHead(200, { 'Content-Type': u.endsWith('.html') ? 'text/html' : u.endsWith('.js') ? 'text/javascript' : 'application/octet-stream' }); res.end(d); }
  catch { res.writeHead(404); res.end(); }
}).listen(0, '127.0.0.1');
await new Promise((r) => server.on('listening', r));
const browser = await chromium.launch({ args: DETERMINISTIC_LAUNCH_ARGS });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, ...DETERMINISTIC_CONTEXT_OPTIONS });
await page.goto(`http://127.0.0.1:${server.address().port}/desktop/dist/index.html?libtest=1&deskx=1`, { waitUntil: 'domcontentloaded', timeout: 60000 });
await page.waitForTimeout(800);
await page.evaluate(() => { document.querySelectorAll('button').forEach((b) => { if (b.textContent.trim() === 'Got it') b.click(); }); if (typeof applyFxLayout === 'function') applyFxLayout(); });
const fixture = (await readFile(path.join(ROOT, 'test/fixtures/portrait.png'))).toString('base64');
await page.evaluate(async (b64) => { const bytes = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0)); await loadFXImages([new File([bytes], 'portrait.png', { type: 'image/png' })]); switchTab('fx'); }, fixture);
await page.waitForTimeout(300);
const CLEAN = (sel) => {
  const el = document.querySelector(sel); if (!el) return null;
  const c = el.cloneNode(true);
  const hidden = (orig) => { const cs = getComputedStyle(orig); return cs.display === 'none' || cs.visibility === 'hidden'; };
  // mark originally-hidden nodes so the playground can keep them hidden
  const o = [el, ...el.querySelectorAll('*')], k = [c, ...c.querySelectorAll('*')];
  // Menus/popovers/badges stay hidden; hidden BUTTONS/INPUTS are state-conditional controls (e.g.
  // Save to Lightroom) and are flagged separately so the playground can reveal them on request.
  o.forEach((n, i) => { if (n === el || !hidden(n)) return; const ctl = n.matches('button,input') || n.querySelector('button,input:not([type=hidden])');
    if (n.matches('.lib-menu,[id$=-menu],[id$=-popover],select') || !ctl) k[i].setAttribute('data-was-hidden', ''); else k[i].setAttribute('data-conditional', ''); });
  for (const n of k) { for (const a of [...n.attributes]) if (/^on/.test(a.name) || a.name === 'style') n.removeAttribute(a.name); }
  return c.outerHTML;
};
const editor = await page.evaluate(CLEAN, '#fx-deskbar');
await page.evaluate(() => { if (window.chromasmithForceLibraryReady) chromasmithForceLibraryReady(); document.getElementById('lib-overlay')?.classList.add('on', 'full'); });
await page.waitForTimeout(300);
const library = await page.evaluate(CLEAN, '#lib-top');
await page.evaluate(() => document.getElementById('lib-filters-panel')?.classList.add('open'));
await page.waitForTimeout(300);
const filters = await page.evaluate(CLEAN, '#lib-filters-panel');
await browser.close(); server.close();
if (!editor || !library) { console.error('bar not found', !!editor, !!library); process.exit(1); }
await writeFile('design/prototypes/swiss-kinetic/bars.js', '// Generated by scripts/redesign-capture-bars.mjs from the running app. Do not edit.\nwindow.REAL_BARS = ' + JSON.stringify({ library, editor, filters }) + ';\n');
console.log('bars.js: library', library.length, 'chars; editor', editor.length, 'chars; filters', (filters || '').length, 'chars');
