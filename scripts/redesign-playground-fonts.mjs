// Copies the app's embedded Gramatika @font-face rules (chromasmith-22.html) into the redesign
// playground, so the playground renders in the exact faces the app ships — never re-typed.
// Usage: node scripts/redesign-playground-fonts.mjs
import { readFile, writeFile } from 'node:fs/promises';
const src = await readFile('chromasmith-22.html', 'utf8');
const faces = src.match(/@font-face\{font-family:'Gramatika';[^}]*\}/g) || [];
if (faces.length !== 4) { console.error(`expected 4 Gramatika faces, found ${faces.length}`); process.exit(1); }
await writeFile('design/prototypes/swiss-kinetic/gramatika.css', '/* Generated by scripts/redesign-playground-fonts.mjs from chromasmith-22.html. Do not edit. */\n' + faces.join('\n') + '\n');
console.log('gramatika.css: 4 faces');
